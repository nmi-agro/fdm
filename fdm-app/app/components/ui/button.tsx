/**
 * Returns the class names of a {@link Button} for elements that look like a button, such as a
 * `<Link>`. Classes passed in `className` are merged with the variant classes, so overrides like
 * `p-0` or `h-auto` replace the size defaults instead of competing with them.
 */
function buttonVariants(props?: Parameters<typeof buttonVariantStyles>[0]): string {
  return cn(buttonVariantStyles(props))
}

function Button({
  className,
  variant = "default",
  size = "default",
  ...props
}: ButtonPrimitive.Props & VariantProps<typeof buttonVariantStyles>) {
  return (
    <ButtonPrimitive
      data-slot="button"
      className={buttonVariants({ variant, size, className })}
      {...props}
    />
  )
}

